"""Render docs/LLM_LOINC_EVAL.md from the eval results (eval.py): the holdout first, the tuned dev set after it."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import config as cfg  # noqa: E402

SLICE_NAMES = {"mimic": "MIMIC", "feed": "Riverside feed", "all": "Both"}
MODEL_NAMES = {"claude-haiku-5-5": "Claude Haiku 5.5", "claude-sonnet-5-5": "Claude Sonnet 5.5"}
N_ERRORS = 10


def pct(r):
    if not r or not r["n"]:
        return "n/a"
    return f"{r['rate'] * 100:.0f}% ({r['low'] * 100:.0f} to {r['high'] * 100:.0f})"


def frac(r):
    return f"{r['k']}/{r['n']}" if r and r["n"] else ""


def ms(x):
    return "" if x is None else f"{x / 1000:.1f} s"


def money(x):
    return f"${x:.4f}"


def label(name):
    """'claude-haiku-5-5 v2' -> 'Claude Haiku 5.5, prompt v2'."""
    if name == "lexical_baseline":
        return "Lexical baseline"
    model, _, version = name.partition(" ")
    return MODEL_NAMES.get(model, model) + (f", prompt {version}" if version else "")


def overlap(a, b):
    return a["low"] <= b["high"] and b["low"] <= a["high"]


def versus(m, b):
    diff = (m["rate"] - b["rate"]) * 100
    return f"{abs(diff):.0f} points {'above' if diff > 0 else 'below'}" if round(diff) else "level with"


def outside_candidates(res):
    """Suggested codes (choice or top 3) that were not candidates, dev and holdout together."""
    n = res["suggested_outside_candidates"]
    for r in res["holdout"]["records"]:
        for d in r["rankers"].values():
            n += sum(1 for c in ([d["choice"]] if d["choice"] else []) + d["top3"] if c not in r["candidates"])
    return n


def render(res):
    out = []
    w = out.append
    ho = res["holdout"]
    w("# LLM assisted LOINC mapping: accuracy eval (demo)")
    w("")
    w(f"Generated by `terminology/llm_loinc/eval.py` on {res['date']}. Two sets: a **holdout** of {ho['pairs']} pairs "
      f"that no prompt or retrieval choice ever saw (the headline), and the **dev set** of {res['gold']['all']} pairs, "
      "on which prompt v2 was written (tuned, so not a headline). The data is demo data: the MIMIC IV demo "
      "(deidentified), the MIMIC III demo's lab dictionary and the invented Riverside General feed.")
    w("")
    w(f"**Frozen on {ho['frozen_on']}, before the holdout was built:** prompt v2, sha256 "
      f"`{ho['frozen']['prompt_v2_sha256']}`, and the retrieval code `loinc_index.py`, sha256 "
      f"`{ho['frozen']['loinc_index_py_sha256']}`. A test fails if either changes. The confidence threshold was chosen "
      "on the dev set before the holdout ran, and the holdout ran once.")
    w("")
    render_holdout(res, w)
    render_dev(res, w)
    render_limits(res, w)
    render_spend(res, w)
    w("## Reproduce")
    w("")
    w("```bash")
    w("python3 -m pip install -r terminology/llm_loinc/requirements.txt")
    w(f"curl -L -o data/mimic_raw/D_LABITEMS_mimic3.csv {cfg.MIMIC3_URL}")
    w("python3 terminology/llm_loinc/loinc_index.py build        # data/loinc/Loinc.csv and MapTo.csv needed")
    w("python3 terminology/llm_loinc/eval.py run --dry-run       # calls not cached yet, estimated cost")
    w("python3 terminology/llm_loinc/eval.py run --max-calls 220")
    w("python3 terminology/llm_loinc/eval.py spend               # every call so far and its cost")
    w("```")
    w("")
    w("With the cache in `data/llm_cache` a rerun makes no API call and writes the same tables.")
    w("")
    w("## LOINC notice")
    w("")
    w(cfg.LOINC_NOTICE)
    w("")
    return "\n".join(out)


