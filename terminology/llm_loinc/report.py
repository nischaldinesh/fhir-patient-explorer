def example_errors(res, models, n=N_ERRORS):
    """Up to n wrong dev answers: gold code shown, then gold code not retrieved, then the abstention test."""
    kinds = [
        ("gold code shown", lambda r: r["case"] == "main" and r["retrieval_lenient"] is not None,
         lambda d: not d["lenient"]),
        ("gold code not retrieved", lambda r: r["case"] == "main" and r["retrieval_lenient"] is None,
         lambda d: d["choice"] is not None),
        ("abstention test", lambda r: r["case"] == "abstention", lambda d: not d["abstained"]),
    ]
    out = []
    records = sorted(res["records"], key=lambda r: r["local_id"])
    for kind, case_ok, wrong in kinds:
        per_model = {m: [dict(r, model=m, kind=kind, choice=r["rankers"][m]["choice"],
                              choice_name=r["rankers"][m]["choice_name"], reason=r["rankers"][m]["reason"])
                         for r in records if case_ok(r) and wrong(r["rankers"][m]) and not r["rankers"][m]["error"]]
                     for m in models}
        while len(out) < n and any(per_model.values()):
            for m in models:
                if per_model[m] and len(out) < n:
                    out.append(per_model[m].pop(0))
    return out
